"""Write docs/test-report.md from the latest backend and frontend test outputs.

Run through `make report`, which produces the inputs first:
- backend/reports/junit.xml and backend/reports/coverage.md (pytest + coverage)
- frontend/reports/vitest.json (Vitest JSON reporter)
"""

import json
import subprocess
import xml.etree.ElementTree as ElementTree
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def backend_summary() -> tuple[str, str]:
    suite = ElementTree.parse(ROOT / "backend/reports/junit.xml").getroot()
    if suite.tag == "testsuites":
        suite = suite[0]
    total = int(suite.get("tests", 0))
    failed = int(suite.get("failures", 0)) + int(suite.get("errors", 0))
    skipped = int(suite.get("skipped", 0))
    passed = total - failed - skipped
    line = f"{passed} passed, {failed} failed, {skipped} skipped ({total} total)"
    coverage = (ROOT / "backend/reports/coverage.md").read_text().strip()
    return line, coverage


def frontend_summary() -> str:
    results = json.loads((ROOT / "frontend/reports/vitest.json").read_text())
    return (
        f"{results['numPassedTests']} passed, {results['numFailedTests']} failed "
        f"({results['numTotalTests']} tests in {len(results['testResults'])} files)"
    )


def main() -> None:
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip()
    backend_line, coverage = backend_summary()
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    report = f"""# Test report

Generated by `make report` at {generated}, from the working tree on top of commit `{commit}`.

| Suite | Result |
| --- | --- |
| Backend (pytest, real PostgreSQL via Testcontainers) | {backend_line} |
| Frontend (Vitest + Testing Library + MSW) | {frontend_summary()} |

## Backend coverage

{coverage}

Reproduce with `make report` (Docker must be running), or run the suites
individually with `make test-backend` and `make test-frontend`.
"""
    (ROOT / "docs/test-report.md").write_text(report)
    print(f"Wrote docs/test-report.md: backend {backend_line}")


if __name__ == "__main__":
    main()
